#!/usr/bin/env python3
"""Generate the title banner, assets/art/banner.svg (D113, Phase 9 P9-19), 1280x320.

Style A, flat like the icon: the slate tile, three chests on the left drawn after the icon's chest
(the rune on the front one only), and the wooden sign (scripts/art/panel.py) on the right. The banner
sits at the top of the player guide and every store page; it shows no game interface.

Usage: scripts/art/banner.py [--out DIR]"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import panel  # noqa: E402
import wordmark  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent.parent
BW, BH = 1280, 320
# the sign fills the right side; its scale is set by the width left of the margin
SIGN_X, SIGN_RIGHT = 664, 1250
SIGN_SCALE = (SIGN_RIGHT - SIGN_X) / panel.W
SIGN_Y = (BH - panel.H * SIGN_SCALE) / 2

CHEST = '''<symbol id="chest" viewBox="10 62 236 148">
 <rect x="14" y="132" width="24" height="30" rx="8" fill="#4e2a12"/>
 <rect x="218" y="132" width="24" height="30" rx="8" fill="#4e2a12"/>
 <path d="M34 96 H222 L236 196 H20 Z" fill="url(#chestWood)"/>
 <path d="M40 130 H216 M36 164 H220" stroke="#4a2810" stroke-width="3"/>
 <path d="M34 96 H222 L223 104 H33 Z" fill="#3a1e0a"/>
 <path d="M46 70 H210 L230 96 H26 Z" fill="#8a5530"/>
 <path d="M60 78 H196 M50 87 H206" stroke="#6b3d1c" stroke-width="3"/>
 <path d="M26 92 H230 V100 H26 Z" fill="#4e2a12"/>
 <rect x="123" y="98" width="10" height="31.5" rx="3" fill="#50535a"/>
 <circle cx="128" cy="153.5" r="27" fill="#4a2810" stroke="#50535a" stroke-width="7"/>
</symbol>'''


def svg():
    # the front chest is 300 wide at (176, 88); the rune is placed in the chest's own coordinates
    rune = (f'<g transform="translate(176 88) scale({300 / 236:.4f}) translate(-10 -62)">'
            f'<path d="{wordmark.RUNE}" fill="{wordmark.GROOVE}" stroke="{wordmark.GROOVE}" stroke-width="6" stroke-linejoin="round" transform="translate(2 3)"/>'
            f'<path d="{wordmark.RUNE}" fill="{wordmark.CREAM}"/></g>')
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- YAVSOS title banner. Original artwork for the YAVSOS project, generated by scripts/art/banner.py. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {BW} {BH}" width="{BW}" height="{BH}">
 <defs>
  <radialGradient id="glow" cx="38%" cy="70%" r="70%"><stop offset="0" stop-color="#4a3a24"/><stop offset="1" stop-color="#1e2126"/></radialGradient>
  <linearGradient id="chestWood" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#7f4a25"/><stop offset="1" stop-color="#5a2f14"/></linearGradient>
  {CHEST}
{panel.defs()}
 </defs>
 <rect width="{BW}" height="{BH}" rx="32" fill="url(#glow)"/>
 <rect x="10" y="10" width="{BW - 20}" height="{BH - 20}" rx="24" fill="none" stroke="#f1e6c8" stroke-width="1.5" opacity="0.08"/>
 <!-- floor and chests, the small ones behind -->
 <path d="M48 276 H640" stroke="#141619" stroke-width="12" stroke-linecap="round" opacity="0.7"/>
 <use href="#chest" x="36" y="164" width="180" height="113"/>
 <use href="#chest" x="440" y="152" width="200" height="125"/>
 <use href="#chest" x="176" y="88" width="300" height="188"/>
 {rune}
 <!-- the sign -->
 <g transform="translate({SIGN_X} {SIGN_Y:.1f}) scale({SIGN_SCALE:.4f})">
{panel.body()}
 </g>
</svg>
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "assets/art"), help="output directory (default assets/art)")
    args = parser.parse_args()
    out = Path(args.out) / "banner.svg"
    out.write_text(svg())
    print(f"{out} ({BW}x{BH}, sign at scale {SIGN_SCALE:.3f})")
