#!/usr/bin/env python3
"""Generate the status-mark legend, assets/art/mark-{ok,caution,broken,off}.svg (D113, Phase 9 P9-19): one
small image per mark for the guide's "Status marks" list, in place of the ✔ ! 𐄂 ⁃ characters that not every
font has. Drawn from the panel's own numbers, not traced: a 24-unit disc of 50% black, a 15-unit glyph from
the 32-unit sprite grid (src/YAVSOS/Interface/PanelArt.cs; y counts up there, flipped here), the colours of
src/YAVSOS/Interface/RulePanel.cs (Ok, Caution, Bad, Off). The "!" is X49 (D114). Export the PNGs at their
natural 24 px, since the stores show inline images at pixel size.

Usage: scripts/art/marks.py [--out DIR]"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SIZE = 24
MARKS = {  # name: colour, glyph lines on the 32 grid (y up, as in the sprite), what the guide says
    "ok": ("#80D480", [((5, 16), (13, 7)), ((13, 7), (27, 25))], "green check: everything is active"),
    "caution": ("#F0BF4F", [((16, 13), (16, 27)), ((16, 6), (16, 6))], "amber !: something to look at, or partly working"),
    "broken": ("#F06B5C", [((6, 6), (26, 26)), ((6, 26), (26, 6))], "red cross: not working"),
    "off": ("#99948A", [((8, 16), (24, 16))], "grey dash: turned off by a setting"),
}
GLYPH_STROKE = 4.4  # on the 32 grid


def mark(colour, lines, size=SIZE):
    c, r = size / 2, size / 2 - 1
    s = (15 / 32) * (size / 24)
    d = " ".join(f"M{x0} {31 - y0} L{x1} {31 - y1}" for (x0, y0), (x1, y1) in lines)
    return (f'<circle cx="{c}" cy="{c}" r="{r}" fill="#000" opacity="0.5"/>'
            f'<path d="{d}" fill="none" stroke="{colour}" stroke-width="{GLYPH_STROKE}" stroke-linecap="round" stroke-linejoin="round" '
            f'transform="translate({c} {c}) scale({s:.4f}) translate(-15.5 -15.5)"/>')


def svg(name):
    colour, lines, what = MARKS[name]
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- YAVSOS status mark, {what}. Drawn after the panel's own mark (PanelArt, RulePanel); generated by scripts/art/marks.py. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}" width="{SIZE}" height="{SIZE}">
{mark(colour, lines)}
</svg>
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "assets/art"), help="output directory (default assets/art)")
    args = parser.parse_args()
    for name in MARKS:
        out = Path(args.out) / f"mark-{name}.svg"
        out.write_text(svg(name))
        print(out)
