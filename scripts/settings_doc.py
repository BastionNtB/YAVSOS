#!/usr/bin/env python3
"""Write docs/SETTINGS.md from the settings the plugin binds (D102).

The setting names, defaults, ranges, who sets them and their descriptions are read from
src/YAVSOS/Configuration/PluginSettings.cs, so the reference says what the configuration
manager says. Edit a setting's description in the code, never in the generated file.

  settings_doc.py          rewrite docs/SETTINGS.md
  settings_doc.py --check  exit 1 if docs/SETTINGS.md is out of date (package.py runs this)

A Bind call this script can't read fails it instead of being left out.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src/YAVSOS/Configuration/PluginSettings.cs"
CORE = ROOT / "src/YAVSOS.Core"
TARGET = ROOT / "docs/SETTINGS.md"
SECTIONS = ["Server", "Cleanup", "Stash", "Controls"]
KEYS = {"Period": ".", "Comma": ",", "LeftControl": "Ctrl", "RightControl": "Ctrl", "LeftShift": "Shift",
        "RightShift": "Shift", "LeftAlt": "Alt", "RightAlt": "Alt", "Mouse2": "Middle mouse",
        "Mouse3": "Mouse 4", "Mouse4": "Mouse 5"}

INTRO = """# YAVSOS settings

<!-- GENERATED by scripts/settings_doc.py from src/YAVSOS/Configuration/PluginSettings.cs.
Do not edit by hand: change a setting's description in the code and run the script. -->

Every setting YAVSOS has, as the configuration manager shows it. Change them in game with a
configuration manager (F1 with BepInEx ConfigurationManager), or in
`BepInEx/config/com.bastionntb.yavsos.cfg`.

**Who sets what.** On a server with YAVSOS, the server decides everything under **Server**,
and its categories file applies to everyone. While `LockSharedPolicy` is on, only admins can
change those. Everything under **Cleanup**, **Stash** and **Controls** is each player's own.
Single-player and client-only games use your own file for all of them.

**With AzuAutoStore.** AzuAutoStore does the stashing with its own keys, range and hotbar
settings, so the **Stash** settings are read-only and kept for when it's removed, and
`AllowStashing` has no effect. `MaximumRange` and `MaximumChests` then limit cleanup only.
Cleanup is Ctrl plus AzuAutoStore's store key.
"""


def fail(message):
    raise SystemExit(f"settings_doc: {message}")


def split_args(text):
    """Top-level comma-separated arguments of a C# call, respecting strings and brackets."""
    args, depth, current, i = [], 0, [], 0
    while i < len(text):
        ch = text[i]
        if ch == '"':
            j = i + 1
            while text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            current.append(text[i:j + 1])
            i = j + 1
            continue
        if ch in "([{<":
            depth += 1
        elif ch in ")]}>":
            depth -= 1
        if ch == "," and depth == 0:
            args.append("".join(current).strip())
            current = []
        else:
            current.append(ch)
        i += 1
    if "".join(current).strip():
        args.append("".join(current).strip())
    return args


def call_body(text, open_paren):
    """The text between a call's parentheses, from the index of its "("."""
    depth, i = 0, open_paren
    while True:
        ch = text[i]
        if ch == '"':
            i += 1
            while text[i] != '"':
                i += 2 if text[i] == "\\" else 1
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return text[open_paren + 1:i]
        i += 1


def string_value(expr):
    """A C# string expression: one literal, or literals joined with +; a Stash(...) wrapper is unwrapped."""
    expr = expr.strip()
    wrapped = re.fullmatch(r"Stash\((.*)\)", expr, re.S)
    if wrapped:
        return string_value(wrapped.group(1))[0], True
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', expr)
    if not parts or re.sub(r'"((?:[^"\\]|\\.)*)"|\+|\s', "", expr):
        fail(f"can't read description {expr[:60]!r}")
    return "".join(p.replace('\\"', '"').replace("\\\\", "\\") for p in parts), False


def constant(name):
    """Resolve Namespace.Type.Name to an integer constant declared in YAVSOS.Core."""
    type_name, field = name.split(".")[-2:]
    for path in CORE.rglob(f"{type_name}.cs"):
        found = re.search(rf"\bconst\s+int\b[^;]*\b{field}\s*=\s*(-?\d+)", path.read_text())
        if found:
            return found.group(1)
    fail(f"can't resolve constant {name}")


def number(expr):
    expr = expr.strip()
    if re.fullmatch(r"-?\d+(\.\d+)?f?", expr):
        return expr.rstrip("f")
    if re.fullmatch(r"[\w.]+", expr):
        return constant(expr)
    fail(f"can't read value {expr!r}")


def value(expr):
    expr = expr.strip()
    if expr in ("true", "false"):
        return "on" if expr == "true" else "off"
    shortcut = re.fullmatch(r"new KeyboardShortcut\((.*)\)", expr, re.S)
    if shortcut:
        keys = [k.strip().split(".")[-1] for k in split_args(shortcut.group(1))]
        main, modifiers = keys[0], keys[1:]
        return " + ".join([KEYS.get(k, k) for k in modifiers] + [KEYS.get(main, main)])
    return number(expr)


def unit(description, text):
    return f"{text} m" if "metres" in description and re.fullmatch(r"[\d.–-]+", text) else text


def read_settings():
    text = SOURCE.read_text()
    settings = []
    for match in re.finditer(r"(?<![\w.])(file\.Bind|Bind)\(", text):
        args = split_args(call_body(text, match.end() - 1))
        if match.group(1) == "Bind" and args[:2] == ["file", "sync"]:
            section, key, default, description, shared = args[2:7]
            rest = args[7:]
        elif match.group(1) == "file.Bind" and args[0].startswith('"'):
            section, key, default, description = args[:4]
            shared, rest = "true", []
        elif match.group(1) == "file.Bind" and args[0] in ("old", "section"):
            continue  # MigrateRenamed's read-once old key, and the wrapper's own call
        else:
            fail(f"can't read Bind call at offset {match.start()}: {args[:3]}")
        description = string_value(description)[0]
        allowed = ""
        for arg in rest:
            bounds = re.fullmatch(r"new AcceptableValueRange<\w+>\((.*)\)", arg.strip(), re.S)
            if bounds:
                low, high = (number(b) for b in split_args(bounds.group(1)))
                allowed = f"{low}–{high}"
        settings.append({"section": string_value(section)[0], "key": string_value(key)[0],
                         "default": value(default), "allowed": allowed, "shared": shared.strip() == "true",
                         "description": description})
    if not settings:
        fail("no settings found")
    unknown = sorted({s["section"] for s in settings} - set(SECTIONS))
    if unknown:
        fail(f"sections without a place in the document: {unknown}")
    return settings


def cell(text):
    return text.replace("|", "\\|")


def render(settings):
    lines = [INTRO]
    for section in SECTIONS:
        rows = sorted((s for s in settings if s["section"] == section), key=lambda s: s["key"])
        if not rows:
            continue
        who = "Set by the server" if all(s["shared"] for s in rows) else "Your own"
        lines += [f"## {section}", "", f"{who}.", "", "| Setting | Default | Allowed | What it does |",
                  "| --- | --- | --- | --- |"]
        for s in rows:
            lines.append(f"| `{s['key']}` | {cell(unit(s['description'], s['default']))} | "
                         f"{cell(unit(s['description'], s['allowed'])) or '—'} | {cell(s['description'])} |")
        lines.append("")
    return "\n".join(lines)


def is_current(text=None):
    """True when docs/SETTINGS.md matches the code."""
    return TARGET.is_file() and TARGET.read_text() == (text if text is not None else render(read_settings()))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/SETTINGS.md is out of date")
    args = parser.parse_args()
    text = render(read_settings())
    if args.check:
        if not is_current(text):
            print("settings_doc: docs/SETTINGS.md is out of date; run scripts/settings_doc.py.", file=sys.stderr)
            sys.exit(1)
        print("docs/SETTINGS.md is current.")
        return
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
