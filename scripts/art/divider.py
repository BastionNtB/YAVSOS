#!/usr/bin/env python3
"""Generate the section dividers, assets/art/divider-left.svg and divider-right.svg (D113, Phase 9 P9-19),
1280x80 each, transparent.

A band of small cut marks (a bar, an angle, a zigzag, two short bars, a slash: abstract cuts in the
letters' chisel style, kept away from real runes) with the icon's chest carrying the rune, anchored at a
quarter or three quarters of the width. The marks fade with distance from the chest, so each divider
points back at the text. The guide alternates left and right down the page. The line colour is the
chests' wood brown, which reads on both a light and a dark page; the chest stands on a soft shadow
rather than a floor line for the same reason.

Usage: scripts/art/divider.py [--out DIR]"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import wordmark  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent.parent
W, H, CY = 1280, 80, 40
BROWN = "#7f4a25"
STEP = 58            # between marks
CHEST_W, CHEST_H = 96, 60
ANCHORS = {"left": 320, "right": 960, "centre": 640}

CHEST = ('<symbol id="chest" viewBox="10 62 236 148">'
         '<rect x="14" y="132" width="24" height="30" rx="8" fill="#4e2a12"/><rect x="218" y="132" width="24" height="30" rx="8" fill="#4e2a12"/>'
         '<path d="M34 96 H222 L236 196 H20 Z" fill="url(#chestWood)"/><path d="M40 130 H216 M36 164 H220" stroke="#4a2810" stroke-width="3"/>'
         '<path d="M34 96 H222 L223 104 H33 Z" fill="#3a1e0a"/><path d="M46 70 H210 L230 96 H26 Z" fill="#8a5530"/>'
         '<path d="M60 78 H196 M50 87 H206" stroke="#6b3d1c" stroke-width="3"/><path d="M26 92 H230 V100 H26 Z" fill="#4e2a12"/>'
         '<rect x="123" y="98" width="10" height="31.5" rx="3" fill="#50535a"/><circle cx="128" cy="153.5" r="27" fill="#4a2810" stroke="#50535a" stroke-width="7"/></symbol>'
         '<linearGradient id="chestWood" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#7f4a25"/><stop offset="1" stop-color="#5a2f14"/></linearGradient>')


def rune(cx, cy, height):
    """The icon rune, `height` tall, centred on (cx, cy), with its groove shadow."""
    s = height / 103
    t = f"translate({cx} {cy}) scale({s:.4f}) translate(-131 -161)"
    return (f'<path d="{wordmark.RUNE}" fill="{wordmark.GROOVE}" stroke="{wordmark.GROOVE}" stroke-width="6" stroke-linejoin="round" transform="{t} translate(2 3)"/>'
            f'<path d="{wordmark.RUNE}" fill="{wordmark.CREAM}" transform="{t}"/>')


def mark(kind, x, y):
    st = wordmark.stroke
    if kind == 0:    # a bar
        parts = [st((x, y - 14), (x, y + 14), 6, 5, bow=1, cut0=2, cut1=-2)]
    elif kind == 1:  # an angle
        parts = [st((x - 8, y - 14), (x + 8, y), 6, 5, cut0=2), st((x + 8, y), (x - 8, y + 14), 5, 6, cut1=2)]
    elif kind == 2:  # a zigzag
        parts = [st((x - 8, y - 13), (x + 6, y - 4), 5, 5), st((x + 6, y - 4), (x - 6, y + 4), 5, 5), st((x - 6, y + 4), (x + 8, y + 13), 5, 5)]
    elif kind == 3:  # two short bars
        parts = [st((x - 5, y - 13), (x - 5, y - 1), 5, 4), st((x + 5, y + 1), (x + 5, y + 13), 5, 4)]
    else:            # a slash
        parts = [st((x + 7, y - 14), (x - 7, y + 14), 6, 5, bow=1.5, cut0=2, cut1=2)]
    return "".join(f'<path d="{d}"/>' for d in parts)


def body(anchor):
    cx = ANCHORS[anchor]
    out = [f'<ellipse cx="{cx}" cy="{CY + 29}" rx="{CHEST_W * 0.52:.0f}" ry="4" fill="{wordmark.GROOVE}" opacity="0.3"/>',
           f'<use href="#chest" x="{cx - CHEST_W / 2:.0f}" y="{CY - 31}" width="{CHEST_W}" height="{CHEST_H}"/>',
           rune(cx, CY + 5, 30)]
    for i in range(-24, 25):
        if abs(i) < 2:
            continue
        x = cx + i * STEP
        if not 60 < x < W - 60:
            continue
        far = abs(i) / 9
        out.append(f'<g fill="{BROWN}" opacity="{max(0.12, 1 - far * 0.95):.2f}">{mark((abs(i) * 3) % 5, x, CY)}</g>')
    return "\n".join(out)


def svg(anchor):
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- YAVSOS section divider, chest at the {anchor}. Original artwork, generated by scripts/art/divider.py. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">
 <defs>{CHEST}</defs>
{body(anchor)}
</svg>
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "assets/art"), help="output directory (default assets/art)")
    args = parser.parse_args()
    for anchor in ("left", "right"):
        out = Path(args.out) / f"divider-{anchor}.svg"
        out.write_text(svg(anchor))
        print(out)
