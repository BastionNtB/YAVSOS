#!/usr/bin/env python3
"""Generate the full-name block, assets/art/name-block.svg (D113, Phase 9 P9-19).

"Yet Another Valheim Storage Organization System" in Marcellus capitals, two lines, flush on both
edges: each line's size is solved so its ink is exactly the word mark's width (scripts/art/wordmark.py,
706 units). The initial of each word is cream, the rest tan. The glyphs are written as paths from
assets/art/fonts/Marcellus-Regular.ttf (OFL, licence beside it), so the SVG needs no font installed.
Kerning is not applied; the capitals are tracked a little instead.

Usage: scripts/art/nameblock.py [--out DIR]"""
import argparse
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent.parent
FONT = ROOT / "assets/art/fonts/Marcellus-Regular.ttf"
CREAM, TAN = "#f1e6c8", "#c9b48a"
LINES = [["Yet", "Another", "Valheim"], ["Storage", "Organization", "System"]]
WIDTH = 706          # the word mark's width
TRACK = 0.04         # letter spacing, em
LINE_GAP = 0.28      # between the lines, em of the upper line

_font = TTFont(FONT)
_upem = _font["head"].unitsPerEm
_cmap = _font.getBestCmap()
_glyphs = _font.getGlyphSet()
_hmtx = _font["hmtx"]
CAP = _font["OS/2"].sCapHeight / _upem


def _bounds(name):
    from fontTools.pens.boundsPen import BoundsPen
    pen = BoundsPen(_glyphs)
    _glyphs[name].draw(pen)
    return pen.bounds  # None for space


def line(words, y, width):
    """One line of capitals with its baseline at y, ink flush from 0 to width. Returns (svg, font size)."""
    text = " ".join(w.upper() for w in words)
    names = [_cmap[ord(c)] for c in text]
    advances = [_hmtx[n][0] for n in names]
    lsb = _bounds(names[0])[0]
    rsb = advances[-1] - _bounds(names[-1])[2]
    ink = (sum(advances) - lsb - rsb) / _upem
    fs = width / (ink + (len(names) - 1) * TRACK)
    k = fs / _upem
    out, x, word_i, first = [], -lsb * k, 0, True
    for ch, name, adv in zip(text, names, advances):
        if ch == " ":
            word_i, first = word_i + 1, True
        else:
            pen = SVGPathPen(_glyphs)
            _glyphs[name].draw(TransformPen(pen, (k, 0, 0, -k, x, y)))
            out.append(f'<path d="{pen.getCommands()}" fill="{CREAM if first else TAN}"/>')
            first = False
        x += adv * k + TRACK * fs
    return "\n".join(out), fs


def block(width=WIDTH):
    """The two lines stacked; returns (svg, height)."""
    out, y = [], 0.0
    for i, words in enumerate(LINES):
        probe_fs = line(words, 0, width)[1]
        y += probe_fs * CAP
        svg, fs = line(words, y, width)
        out.append(svg)
        if i < len(LINES) - 1:
            y += fs * LINE_GAP
    return "\n".join(out), y


def svg():
    body, h = block()
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- YAVSOS full name block: Marcellus capitals (OFL, assets/art/fonts/) as paths, two lines flush to the
     word mark's width. Generated by scripts/art/nameblock.py. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {h:.1f}" width="{WIDTH}" height="{h:.1f}">
{body}
</svg>
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "assets/art"), help="output directory (default assets/art)")
    args = parser.parse_args()
    out = Path(args.out) / "name-block.svg"
    out.write_text(svg())
    print(f"{out} ({WIDTH}x{block()[1]:.0f})")
