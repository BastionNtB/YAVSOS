#!/usr/bin/env python3
"""Generate the closing ornament, assets/art/ornament.svg (D113, Phase 9 P9-19), 480x110, transparent:
the icon's rune between two chisel cuts that taper away, for the end of the guide above "Licence and
credits". The cuts are the wood brown, which reads on a light and a dark page.

Usage: scripts/art/ornament.py [--out DIR]"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import divider  # noqa: E402
import wordmark  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent.parent
W, H, CX, CY = 480, 110, 240, 55


def cut(p0, p1, w0, w1, **kw):
    return f'<path d="{wordmark.stroke(p0, p1, w0, w1, **kw)}" fill="{divider.BROWN}"/>'


def body():
    return (cut((CX - 44, CY), (CX - 150, CY + 2), 6, 2, bow=1.5, cut0=2)
            + cut((CX + 44, CY), (CX + 150, CY + 2), 6, 2, bow=-1.5, cut0=-2)
            + divider.rune(CX, CY + 1, 52))


def svg():
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- YAVSOS closing ornament. Original artwork, generated by scripts/art/ornament.py. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">
{body()}
</svg>
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "assets/art"), help="output directory (default assets/art)")
    args = parser.parse_args()
    out = Path(args.out) / "ornament.svg"
    out.write_text(svg())
    print(out)
