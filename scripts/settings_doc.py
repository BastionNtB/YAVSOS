#!/usr/bin/env python3
"""Write docs/SETTINGS.md from the settings the plugin binds (D102).

The setting names, defaults, ranges and who sets them are read from
src/YAVSOS/Configuration/PluginSettings.cs. Each description is the English message
yavsos_setting_<section>_<key> (lower case) in src/YAVSOS/Translations/English/yavsos.json
(P10-04), so the reference says what the Configuration Manager says in English. Edit a
description in the English file, never in the generated file.

  settings_doc.py          rewrite docs/SETTINGS.md
  settings_doc.py --check  exit 1 if docs/SETTINGS.md is out of date (package.py runs this)

A Bind call this script can't read, a description key that isn't the one derived from the
setting's section and name, or a message the English file lacks fails it instead of being
left out.
"""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src/YAVSOS/Configuration/PluginSettings.cs"
ENGLISH = ROOT / "src/YAVSOS/Translations/English/yavsos.json"
CORE = ROOT / "src/YAVSOS.Core"
TARGET = ROOT / "docs/SETTINGS.md"
SECTIONS = ["Server", "Cleanup", "Stash", "Controls"]
KEYS = {"Period": ".", "Comma": ",", "LeftControl": "Ctrl", "RightControl": "Ctrl", "LeftShift": "Shift",
        "RightShift": "Shift", "LeftAlt": "Alt", "RightAlt": "Alt", "Mouse2": "Middle mouse",
        "Mouse3": "Mouse 4", "Mouse4": "Mouse 5"}
# Player-facing names for enum members and default colors. A member or color missing here fails the script,
# so a new one gets a readable name instead of a code identifier.
ENUM_NAMES = {"None": "None", "SmallItemPuff": "small-item puff", "SmelterPuff": "smelter puff",
              "FermenterPuff": "fermenter puff", "LootSparkle": "loot sparkle", "PickSparkle": "pick sparkle",
              "AutoPickupShimmer": "auto-pickup shimmer"}
COLOR_NAMES = {"FFC740": "gold", "80B8FF": "cool blue", "FF6B33": "red-orange"}

INTRO = """# YAVSOS settings

<!-- GENERATED by scripts/settings_doc.py from src/YAVSOS/Configuration/PluginSettings.cs and
src/YAVSOS/Translations/English/yavsos.json. Do not edit by hand: change a setting's
description in the English file and run the script. -->

Every setting YAVSOS has, as the Configuration Manager shows it in English. Change them in
game with a Configuration Manager (F1 with BepInEx ConfigurationManager), or in
`BepInEx/config/com.bastionntb.yavsos.cfg`.

**Who sets what.** On a server with YAVSOS, the server decides everything under **Server**,
and its categories file applies to everyone. While `LockSharedPolicy` is on, only admins can
change those. Everything under **Cleanup**, **Stash** and **Controls** is each player's own.
Single-player and client-only games use your own file for all of them.

**With AzuAutoStore.** AzuAutoStore does the stashing with its own keys, range and hotbar
settings, so the **Stash** settings are read-only and kept for when it's removed, and
`AllowStashing` has no effect. `MaximumRange` and `MaximumChests` then limit cleanup only.
Cleanup is the cleanup key's modifier (Ctrl by default) plus AzuAutoStore's stash key.
"""


def fail(message):
    raise SystemExit(f"settings_doc: {message}")


def split_args(text):
    """Top-level comma-separated arguments of a C# call, respecting strings and brackets."""
    args, depth, current, i = [], 0, [], 0
    while i < len(text):
        ch = text[i]
        if ch == '"':
            j = i + 1
            while text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            current.append(text[i:j + 1])
            i = j + 1
            continue
        if ch in "([{<":
            depth += 1
        elif ch in ")]}>":
            depth -= 1
        if ch == "," and depth == 0:
            args.append("".join(current).strip())
            current = []
        else:
            current.append(ch)
        i += 1
    if "".join(current).strip():
        args.append("".join(current).strip())
    return args


def call_body(text, open_paren):
    """The text between a call's parentheses, from the index of its "("."""
    depth, i = 0, open_paren
    while True:
        ch = text[i]
        if ch == '"':
            i += 1
            while text[i] != '"':
                i += 2 if text[i] == "\\" else 1
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return text[open_paren + 1:i]
        i += 1


def string_value(expr):
    """A C# string expression: one literal, or literals joined with +."""
    expr = expr.strip()
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', expr)
    if not parts or re.sub(r'"((?:[^"\\]|\\.)*)"|\+|\s', "", expr):
        fail(f"can't read string {expr[:60]!r}")
    return "".join(p.replace('\\"', '"').replace("\\\\", "\\") for p in parts)


def english_messages():
    """The English message file, as Jotunn reads it: one flat object of strings."""
    try:
        data = json.loads(ENGLISH.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        fail(f"can't read {ENGLISH.relative_to(ROOT)}: {error}")
    if not isinstance(data, dict):
        fail(f"{ENGLISH.relative_to(ROOT)} is not one JSON object")
    for key, text in data.items():
        if not isinstance(text, str):
            fail(f"{ENGLISH.relative_to(ROOT)}: {key} is not a string")
    return data


PLACEHOLDER = re.compile(r"\{\{(\w+)\}\}")
MESSAGE_OF = re.compile(r'Message\.Of\("(yavsos_\w+)"\)')
WITH = re.compile(r'\.With\("(\w+)",\s*(?:"((?:[^"\\]|\\.)*)"|Message\.Of\("(yavsos_\w+)"\))\)')


def message_text(key, english):
    if key not in english:
        fail(f"{key} is not in {ENGLISH.relative_to(ROOT)}")
    return english[key]


def description(expr, section, key, english):
    """
    The English description of one setting. The Bind call passes Message.Of("yavsos_setting_<section>_<key>"), maybe
    wrapped in Stash(...) (AzuAutoStore's read-only prefix, left out here) or Describe(...) (the direct file.Bind), and
    followed by .With(name, "literal") or .With(name, Message.Of("key")); the text comes from the English file.
    """
    expr = expr.strip()
    wrapped = re.fullmatch(r"(?:Stash|Describe)\((.*)\)", expr, re.S)
    if wrapped:
        expr = wrapped.group(1).strip()
    head = MESSAGE_OF.match(expr)
    if not head:
        fail(f"{section}.{key}: can't read description {expr[:60]!r}")
    derived = f"yavsos_setting_{section}_{key}".lower()
    if head.group(1) != derived:
        fail(f"{section}.{key}: its description key is {head.group(1)}, not {derived}")
    values, at = {}, head.end()
    while at < len(expr):
        found = WITH.match(expr, at)
        if not found:
            fail(f"{section}.{key}: can't read {expr[at:at + 60]!r}")
        name, literal, nested = found.groups()
        if nested:
            inner = message_text(nested, english)
            if PLACEHOLDER.search(inner):
                fail(f"{section}.{key}: {nested} has placeholders, which this script doesn't fill")
            values[name] = inner
        else:
            values[name] = literal.replace('\\"', '"').replace("\\\\", "\\")
        at = found.end()
    text = message_text(derived, english)
    needed = set(PLACEHOLDER.findall(text))
    if needed != set(values):
        fail(f"{section}.{key}: {derived} has placeholders {sorted(needed)}, the code gives {sorted(values)}")
    return PLACEHOLDER.sub(lambda m: values[m.group(1)], text)


def constant(name):
    """Resolve Namespace.Type.Name to an integer constant declared in YAVSOS.Core."""
    type_name, field = name.split(".")[-2:]
    for path in CORE.rglob(f"{type_name}.cs"):
        found = re.search(rf"\bconst\s+int\b[^;]*\b{field}\s*=\s*(-?\d+)", path.read_text())
        if found:
            return found.group(1)
    fail(f"can't resolve constant {name}")


def enum_members(type_name):
    """The members of an enum declared in YAVSOS.Core, in declaration order."""
    for path in CORE.rglob("*.cs"):
        found = re.search(rf"\benum\s+{type_name}\s*\{{([^}}]*)\}}", path.read_text())
        if found:
            return [m.split("=")[0].strip() for m in found.group(1).split(",") if m.strip()]
    return None


def enum_name(member):
    if member not in ENUM_NAMES:
        fail(f"no player-facing name for enum member {member} (add it to ENUM_NAMES)")
    return ENUM_NAMES[member]


def color(expr):
    """new UnityEngine.Color(r, g, b, a) as its name and hex, such as gold (`FFC740`); alpha is ignored."""
    parts = [float(p.strip().rstrip("f")) for p in split_args(expr)][:3]
    hexed = "".join(f"{round(p * 255):02X}" for p in parts)
    if hexed not in COLOR_NAMES:
        fail(f"no name for default color {hexed} (add it to COLOR_NAMES)")
    return f"{COLOR_NAMES[hexed]} (`{hexed}`)"


def number(expr):
    expr = expr.strip()
    if re.fullmatch(r"-?\d+(\.\d+)?f?", expr):
        return expr.rstrip("f")
    if re.fullmatch(r"[\w.]+", expr):
        return constant(expr)
    fail(f"can't read value {expr!r}")


def value(expr):
    expr = expr.strip()
    if expr in ("true", "false"):
        return "on" if expr == "true" else "off"
    shortcut = re.fullmatch(r"new KeyboardShortcut\((.*)\)", expr, re.S)
    if shortcut:
        keys = [k.strip().split(".")[-1] for k in split_args(shortcut.group(1))]
        main, modifiers = keys[0], keys[1:]
        return " + ".join([KEYS.get(k, k) for k in modifiers] + [KEYS.get(main, main)])
    colour = re.fullmatch(r"new (?:UnityEngine\.)?Color\((.*)\)", expr, re.S)
    if colour:
        return color(colour.group(1))
    member = re.fullmatch(r"[\w.]+\.(\w+)\.(\w+)", expr)
    if member and enum_members(member.group(1)):
        return enum_name(member.group(2))
    return number(expr)


def allowed_for(default_expr):
    """The Allowed cell for enum and color settings, which have no AcceptableValueRange."""
    expr = default_expr.strip()
    if re.fullmatch(r"new (?:UnityEngine\.)?Color\(.*\)", expr, re.S):
        return "any color"
    member = re.fullmatch(r"[\w.]+\.(\w+)\.(\w+)", expr)
    members = enum_members(member.group(1)) if member else None
    return ", ".join(enum_name(m) for m in members) if members else ""


def unit(description, text):
    """A distance in meters gets its unit (US spelling, D136)."""
    return f"{text} m" if re.search(r"\bmeters\b", description) and re.fullmatch(r"[\d.–-]+", text) else text


def read_settings():
    text = SOURCE.read_text()
    english = english_messages()
    settings = []
    for match in re.finditer(r"(?<![\w.])(file\.Bind|Bind)\(", text):
        args = split_args(call_body(text, match.end() - 1))
        if match.group(1) == "Bind" and args[:2] == ["file", "sync"]:
            section, key, default, said, shared = args[2:7]
            rest = args[7:]
        elif match.group(1) == "file.Bind" and args[0].startswith('"'):
            section, key, default, said = args[:4]
            shared, rest = "true", []  # the locking entry, bound for ServerSync's AddLockingConfigEntry
        elif match.group(1) == "file.Bind" and args[0] in ("old", "section"):
            continue  # MigrateRenamed's read-once old key, and the wrapper's own call
        else:
            fail(f"can't read Bind call at offset {match.start()}: {args[:3]}")
        section, key = string_value(section), string_value(key)
        said = description(said, section, key, english)
        allowed = allowed_for(default)
        for arg in rest:
            bounds = re.fullmatch(r"new AcceptableValueRange<\w+>\((.*)\)", arg.strip(), re.S)
            if bounds:
                low, high = (number(b) for b in split_args(bounds.group(1)))
                allowed = f"{low}–{high}"
        settings.append({"section": section, "key": key,
                         "default": value(default), "allowed": allowed, "shared": shared.strip() == "true",
                         "description": said})
    if not settings:
        fail("no settings found")
    unknown = sorted({s["section"] for s in settings} - set(SECTIONS))
    if unknown:
        fail(f"sections without a place in the document: {unknown}")
    return settings


def cell(text):
    return text.replace("|", "\\|")


def render(settings):
    lines = [INTRO]
    for section in SECTIONS:
        rows = sorted((s for s in settings if s["section"] == section), key=lambda s: s["key"])
        if not rows:
            continue
        who = "Set by the server" if all(s["shared"] for s in rows) else "Your own"
        lines += [f"## {section}", "", f"{who}.", "", "| Setting | Default | Allowed | What it does |",
                  "| --- | --- | --- | --- |"]
        for s in rows:
            lines.append(f"| `{s['key']}` | {cell(unit(s['description'], s['default']))} | "
                         f"{cell(unit(s['description'], s['allowed'])) or '—'} | {cell(s['description'])} |")
        lines.append("")
    return "\n".join(lines)


def is_current(text=None):
    """True when docs/SETTINGS.md matches the code."""
    return TARGET.is_file() and TARGET.read_text() == (text if text is not None else render(read_settings()))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/SETTINGS.md is out of date")
    args = parser.parse_args()
    text = render(read_settings())
    if args.check:
        if not is_current(text):
            print("settings_doc: docs/SETTINGS.md is out of date; run scripts/settings_doc.py.", file=sys.stderr)
            sys.exit(1)
        print("docs/SETTINGS.md is current.")
        return
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
